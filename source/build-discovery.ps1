$ErrorActionPreference = 'Stop'
$extension = Join-Path (Split-Path -Parent $PSScriptRoot) 'chrome-extension'
$core = [IO.File]::ReadAllText((Join-Path $extension 'detection.js')) -replace '(?m)^export ', ''
$body = [IO.File]::ReadAllText((Join-Path $extension 'content-body.js'))
[IO.File]::WriteAllText((Join-Path $extension 'scan-content.js'), "// Generated by source/build-discovery.ps1; edit detection.js and content-body.js.`n(() => {`n'use strict';`n" + $core + "`n" + $body + "`n})();`n", (New-Object Text.UTF8Encoding($false)))
Write-Output 'Built isolated media scanner.'
# Opera uses a popup/full-tab panel when Chrome's sidePanel API is unavailable.
$opera = Join-Path (Split-Path -Parent $PSScriptRoot) 'opera-extension'
New-Item -ItemType Directory -Path $opera -Force | Out-Null
$production = @('background.js','transport.js','panel.js','panel.html','panel.css','i18n.js','setup.html','setup.js','detection.js','discovery.js','media-panel.js','scan-content.js','package.json')
foreach($file in $production){Copy-Item -LiteralPath (Join-Path $extension $file) -Destination (Join-Path $opera $file) -Force}
Copy-Item -LiteralPath (Join-Path $extension 'icons') -Destination $opera -Recurse -Force
$manifest = Get-Content -Raw -Encoding UTF8 -LiteralPath (Join-Path $extension 'manifest.json') | ConvertFrom-Json
$manifest.permissions = @($manifest.permissions | Where-Object {$_ -ne 'sidePanel'})
$manifest.PSObject.Properties.Remove('side_panel')
$manifest.PSObject.Properties.Remove('minimum_chrome_version')
[IO.File]::WriteAllText((Join-Path $opera 'manifest.json'),($manifest | ConvertTo-Json -Depth 12),(New-Object Text.UTF8Encoding($false)))
Write-Output 'Built Opera companion package.'
